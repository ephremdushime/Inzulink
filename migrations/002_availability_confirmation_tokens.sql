CREATE TABLE IF NOT EXISTS public.availability_confirmation_tokens (
  token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id INTEGER NOT NULL REFERENCES public.properties(property_id) ON DELETE CASCADE,
  owner_id INTEGER NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE
    CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL,
  consumed_at TIMESTAMPTZ,
  CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS idx_availability_tokens_property_created
  ON public.availability_confirmation_tokens (property_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_availability_tokens_owner_created
  ON public.availability_confirmation_tokens (owner_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_availability_tokens_pending_expiry
  ON public.availability_confirmation_tokens (expires_at)
  WHERE consumed_at IS NULL;
